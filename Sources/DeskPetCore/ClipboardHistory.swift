import Foundation

/// One thing the user copied.
public struct ClipEntry: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var text: String
    public var copiedAt: Date
    /// The app that was in front when it was copied (display only).
    public var sourceApp: String?

    public init(id: UUID = UUID(), text: String, copiedAt: Date, sourceApp: String?) {
        self.id = id
        self.text = text
        self.copiedAt = copiedAt
        self.sourceApp = sourceApp
    }

    /// First non-empty line, whitespace-collapsed, for list rows.
    public var preview: String {
        let line = text.split(whereSeparator: \.isNewline).first { !$0.trimmingCharacters(in: .whitespaces).isEmpty } ?? ""
        let collapsed = line.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return collapsed.count > 120 ? String(collapsed.prefix(120)) + "…" : collapsed
    }

    public var lineCount: Int { text.split(whereSeparator: \.isNewline).count }
}

/// Recent clipboard text: newest first, de-duplicated, capped, and never
/// holding things password managers mark as secret.
public struct ClipboardHistory: Codable, Equatable, Sendable {
    public static let maxEntries = 30
    /// Bigger copies (whole documents, logs) aren't kept.
    public static let maxLength = 20_000

    public private(set) var entries: [ClipEntry] = []

    public init(entries: [ClipEntry] = []) {
        self.entries = Array(entries.prefix(Self.maxEntries))
    }

    /// Pasteboard types that mean "don't keep this" (nspasteboard.org conventions,
    /// used by 1Password, Bitwarden, KeePassXC, Keychain Access and others).
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Apps whose copies are never kept, whatever types they set.
    public static let privateApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
        "org.keepassxc.keepassxc", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
    ]

    public static func shouldIgnore(types: [String], sourceBundleID: String?) -> Bool {
        if let id = sourceBundleID, privateApps.contains(id) { return true }
        return types.contains { privateTypes.contains($0) }
    }

    /// Adds a copy. Returns false when it isn't worth keeping (blank or huge).
    /// Copying something already in the list moves it to the top.
    @discardableResult
    public mutating func record(_ text: String, at date: Date, sourceApp: String?) -> Bool {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maxLength else { return false }
        if let i = entries.firstIndex(where: { $0.text == text }) {
            var e = entries.remove(at: i)
            e.copiedAt = date
            e.sourceApp = sourceApp ?? e.sourceApp
            entries.insert(e, at: 0)
        } else {
            entries.insert(ClipEntry(text: text, copiedAt: date, sourceApp: sourceApp), at: 0)
            if entries.count > Self.maxEntries { entries.removeLast(entries.count - Self.maxEntries) }
        }
        return true
    }

    public mutating func remove(id: UUID) { entries.removeAll { $0.id == id } }
    public mutating func clear() { entries.removeAll() }

    /// Case- and diacritic-insensitive; every word must appear.
    public func search(_ query: String) -> [ClipEntry] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        guard !words.isEmpty else { return entries }
        return entries.filter { e in
            words.allSatisfy { e.text.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
    }
}

/// "Keep awake" durations offered in menus. nil = until turned off.
public enum KeepAwake {
    public static let presets: [Int?] = [30, 60, 120, nil]
    public static let maxMinutes = 24 * 60

    public static func title(minutes: Int?) -> String {
        guard let m = minutes else { return "Until turned off" }
        if m % 60 == 0 { return m == 60 ? "1 hour" : "\(m / 60) hours" }
        if m > 60 { return "\(m / 60) h \(m % 60) min" }
        return "\(m) minutes"
    }

    /// "1:05 left" style countdown.
    public static func remaining(_ seconds: TimeInterval) -> String {
        let s = max(0, Int(seconds.rounded(.up)))
        let h = s / 3600, m = (s % 3600) / 60
        return h > 0 ? "\(h) h \(m) min left" : "\(max(1, m)) min left"
    }
}
